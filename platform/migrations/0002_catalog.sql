-- Catalog: sections and tags. Seeded from the prototype starter catalog
-- (prototype/local-runtime-only-2026-10-09, backend/server.mjs SECTIONS/TAG_SLUGS).
-- The API returns the full catalog and flags which entries have visible posts;
-- the UI hides empty ones.
CREATE TABLE sections (
  number INTEGER PRIMARY KEY AUTOINCREMENT,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  description TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived'))
);
CREATE TABLE tags (
  number INTEGER PRIMARY KEY AUTOINCREMENT,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived'))
);
